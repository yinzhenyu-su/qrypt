#!/usr/bin/env python3
"""Generate pkg/drive/builtin_schema_gen.go from schema/qrypt.schema.json."""

import json
import os
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
SCHEMA_PATH = os.path.join(ROOT, "schema", "qrypt.schema.json")
OUTPUT_PATH = os.path.join(ROOT, "pkg", "drive", "builtin_schema_gen.go")

TYPE_MAP = {
    "string": "string",
    "integer": "int",
    "boolean": "bool",
    "number": "float",
}

HEADER = """// Code generated by scripts/schema/gen-drive-schema.py; DO NOT EDIT.

package drive

var builtinParamSpecs = map[string]ParamSpec{
"""


def go_string(value):
    return json.dumps(value, ensure_ascii=False)


def param_type(prop):
    if "x-param-type" in prop:
        return prop["x-param-type"]
    return TYPE_MAP.get(prop.get("type", "string"), "string")


def default_string(prop):
    value = prop.get("default")
    if value is None or value == "":
        return ""
    if isinstance(value, bool):
        return str(value).lower()
    return str(value)


def build_spec(definition):
    required = list(definition.get("required", []))
    any_of = []
    for option in definition.get("anyOf", []):
        names = [name for name in option.get("required", []) if name not in required]
        if names:
            any_of.append(names)

    params = []
    for name, prop in definition.get("properties", {}).items():
        fields = [
            f"Name: {go_string(name)}",
            f"Type: {go_string(param_type(prop))}",
        ]
        if name in required:
            fields.append("Required: true")
        if prop.get("x-secret"):
            fields.append("Secret: true")
        if prop.get("description"):
            fields.append(f"Description: {go_string(prop['description'].rstrip('.'))}")
        translations = {
            lang: value["description"]
            for lang, value in prop.get("x-i18n", {}).items()
            if isinstance(value, dict) and value.get("description")
        }
        if translations:
            entries = ", ".join(
                f"{go_string(lang)}: {go_string(text)}"
                for lang, text in sorted(translations.items())
            )
            fields.append(f"DescriptionI18n: map[string]string{{{entries}}}")
        default = default_string(prop)
        if default:
            fields.append(f"Default: {go_string(default)}")
        example = prop.get("x-example", prop.get("example", ""))
        if example:
            fields.append(f"Example: {go_string(str(example))}")
        params.append("\t\t\t{" + ", ".join(fields) + "},")

    lines = ["\t" + go_string(definition["x-driver"]["type"]) + ": {"]
    lines.append("\t\tParams: []ParamDef{")
    lines.extend(params)
    lines.append("\t\t},")
    if required:
        lines.append("\t\tRequired: []string{" + ", ".join(go_string(name) for name in required) + "},")
    if any_of:
        groups = [
            "[]string{" + ", ".join(go_string(name) for name in group) + "}"
            for group in any_of
        ]
        lines.append("\t\tAnyOf: [][]string{" + ", ".join(groups) + "},")
    lines.append("\t},")
    return "\n".join(lines)


def generate():
    schema = json.loads(open(SCHEMA_PATH, encoding="utf-8").read())
    drivers = [
        definition
        for definition in schema.get("definitions", {}).values()
        if isinstance(definition, dict) and "x-driver" in definition
    ]
    drivers.sort(key=lambda definition: definition["x-driver"].get("order", 0))

    body = HEADER
    body += "\n".join(build_spec(definition) for definition in drivers)
    body += "\n}\n"

    with open(OUTPUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)

    result = subprocess.run(["gofmt", "-w", OUTPUT_PATH], capture_output=True, text=True, encoding="utf-8")
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        raise SystemExit(result.returncode)
    print(f"Generated {OUTPUT_PATH}")


if __name__ == "__main__":
    generate()
